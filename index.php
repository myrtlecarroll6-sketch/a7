      <div class="section-header-block">
        <span class="section-pretitle">Frequently Asked Questions</span>
        <h2 class="section-main-heading">Pedagogy & Study Methodology</h2>
        <p class="section-subtext">Common inquiries regarding note-taking systems, cognitive load theory, and memory retention.</p>
      </div>

      <div class="faq-accordion-box">
        <div class="faq-item">
          <button class="faq-trigger" type="button">
            <span>Why is verbatim typing during lectures detrimental to learning?</span>
            <span class="faq-icon">+</span>
          </button>
          <div class="faq-body">
            <p>Typing speed allows students to transcribe lectures verbatim without cognitively processing the material. Studies from Princeton and UCLA demonstrate that handwriting notes forces cognitive summarization, paraphrasing, and concept selection in real-time, resulting in dramatically higher conceptual test performance.</p>
          </div>
        </div>

        <div class="faq-item">
          <button class="faq-trigger" type="button">
            <span>How does the Cornell Cue Column function as an active recall tool?</span>
            <span class="faq-icon">+</span>
          </button>
          <div class="faq-body">
            <p>By writing questions and cues in the 2.5-inch left margin while leaving the note body on the right, you create a built-in flashcard system. During review sessions, fold the page along the margin line or cover the note area, forcing your brain to retrieve answers purely from memory cues.</p>
          </div>
        </div>

        <div class="faq-item">
          <button class="faq-trigger" type="button">
            <span>What is the optimal length of an active recall study session?</span>
            <span class="faq-icon">+</span>
          </button>
          <div class="faq-body">
            <p>Cognitive load theory indicates that intense retrieval practice reaches peak efficiency in 50-minute focused blocks followed by a 10-minute diffuse recovery break. Attempting multi-hour marathon sessions without breaks leads to synaptic fatigue and diminishing returns.</p>
          </div>
        </div>

        <div class="faq-item">
          <button class="faq-trigger" type="button">
            <span>How do visual diagrams enhance text notes according to Dual Coding Theory?</span>
            <span class="faq-icon">+</span>
          </button>
          <div class="faq-body">
            <p>Paivio's Dual Coding Theory proves the human brain processes visual and verbal information through separate neurological channels. When you pair structured written prose with a visual flowchart or concept diagram, you create two distinct associative memory traces in the brain, doubling retrieval accessibility.</p>
          </div>
        </div>
      </div>
